//! What the tools know: commands, their options, assignment and property
//! names. The lists only need to hold what files commonly use: an unknown
//! name is reported only when it is a near miss of a known one.

/// A command and what it takes.
pub struct Spec {
    pub name: &'static str,
    /// Options that take a value.
    pub valued: &'static [&'static str],
    /// Options that take none.
    pub flags: &'static [&'static str],
    /// Whether these are all its options: an unknown one is reported.
    pub closed: bool,
    /// Options it cannot do without.
    pub required: &'static [&'static str],
    /// How many words it needs besides options.
    pub positional: usize,
}

const fn spec(
    name: &'static str,
    valued: &'static [&'static str],
    flags: &'static [&'static str],
    required: &'static [&'static str],
    positional: usize,
) -> Spec {
    Spec {
        name,
        valued,
        flags,
        closed: true,
        required,
        positional,
    }
}

/// A command whose options are not checked.
const fn open(name: &'static str) -> Spec {
    Spec {
        name,
        valued: &[],
        flags: &[],
        closed: false,
        required: &[],
        positional: 0,
    }
}

